"""Проверка миграций схемы БД на тестовой базе (make migrations-check, этап CI «Миграции»).

1. Чистая база создаётся миграциями той же командой, что make migrate.
2. Все миграции откатываются до пустой базы и применяются снова.
3. Схема после миграций совпадает с моделями приложения (alembic check): изменение
   модели без миграции здесь будет найдено.
4. База с данными первой версии схемы обновляется до последней без потери данных.

В конце тестовая база очищается.
"""

import sys

from tools.check_helpers import CheckFailed, ok, require, run_app, step, use_test_database


def main():
    use_test_database()
    # приложение импортируется только после подмены настроек
    from alembic import command
    from alembic.script import ScriptDirectory
    from alembic.util import AutogenerateDiffsDetected
    from sqlalchemy import MetaData, inspect, text

    from app.database import Base, engine
    from app.migrate import alembic_config
    from app.models import material, receipt, supplier, unit, user  # noqa: F401 — регистрирует модели

    config = alembic_config()
    script = ScriptDirectory.from_config(config)
    chain = [rev.revision for rev in reversed(list(script.walk_revisions()))]
    head = script.get_current_head()
    model_tables = set(Base.metadata.tables)

    def tables():
        return set(inspect(engine).get_table_names())

    def version():
        with engine.connect() as conn:
            return conn.execute(text("SELECT version_num FROM alembic_version")).scalar()

    def drop_everything():
        metadata = MetaData()
        metadata.reflect(bind=engine)
        metadata.drop_all(bind=engine)

    print(f"Проверка миграций на базе {engine.url.database}: {' → '.join(chain)}\n")
    try:
        step("Чистая база создаётся миграциями (python -m app.cli migrate)")
        drop_everything()
        out = run_app("migrate")
        require("Схема базы данных актуальна" in out, "команда migrate выполнена без ошибок")
        require(version() == head, f"версия схемы {head} — последняя")
        require(model_tables <= tables(), f"созданы все таблицы: {', '.join(sorted(model_tables))}")

        step("Откат всех миграций и повторное применение")
        command.downgrade(config, "base")
        require(not tables() & model_tables, "после отката до base таблиц приложения нет")
        command.upgrade(config, "head")
        require(version() == head, f"миграции применены снова, версия {head}")

        step("Схема совпадает с моделями (alembic check)")
        try:
            command.check(config)
        except AutogenerateDiffsDetected as exc:
            raise CheckFailed(f"модели и миграции расходятся, нужна миграция:\n{exc}") from exc
        ok("расхождений нет: каждое изменение моделей оформлено миграцией")

        step(f"Обновление базы с данными с версии {chain[0]}")
        command.downgrade(config, chain[0])
        with engine.begin() as conn:
            conn.execute(text("INSERT INTO units (name, short_name) VALUES ('Метка', 'мтк')"))
            conn.execute(
                text(
                    "INSERT INTO materials (name, unit_id, stock) "
                    "SELECT 'migrations-check', id, 12.5 FROM units WHERE short_name = 'мтк'"
                )
            )
        ok(f"в базе версии {chain[0]} есть данные")
        run_app("migrate")
        require(version() == head, f"база обновлена до версии {head}")
        with engine.connect() as conn:
            row = conn.execute(
                text("SELECT stock, min_stock FROM materials WHERE name = 'migrations-check'")
            ).one_or_none()
        require(row is not None and row.stock == 12.5, "данные сохранились")
        require(row.min_stock == 0, "новые столбцы получили значения по умолчанию")
    except CheckFailed as exc:
        print(f"\nПРОВЕРКА НЕ ПРОЙДЕНА: {exc}")
        sys.exit(1)
    finally:
        drop_everything()
    print("\nМиграции в порядке")


if __name__ == "__main__":
    main()
